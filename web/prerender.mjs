// Pre-renders the pages that never depend on who is asking (landing, docs
// for signed-out visitors, 404) into web/build/server/static-pages.js, so
// the Worker serves them as strings: no React work on Workers Free's 10 ms
// CPU budget. Run by `bun run build:web` (Node: react-dom's Bun build is
// not usable from a plain script).
import { writeFile } from "node:fs/promises";
import { createRequestHandler, RouterContextProvider } from "react-router";

export const ORIGIN_TOKEN = "https://__htmlartifact_origin__.invalid";

const dir = new URL("./build/server/", import.meta.url);
const build = await import(new URL("index.js", dir).href);
const handle = createRequestHandler(build, "production");
const { pageContext, originContext } = build.entry.module;

async function render(path, page) {
  const context = new RouterContextProvider();
  context.set(pageContext, page);
  context.set(originContext, ORIGIN_TOKEN);
  const response = await handle(new Request(`${ORIGIN_TOKEN}${path}`), context);
  if (response.status !== 200) throw new Error(`prerender ${path}: ${response.status}`);
  return response.text();
}

const pages = {
  landing: await render("/", { kind: "landing", session: null }),
  docs: await render("/docs", { kind: "docs", session: null }),
  "not-found": await render("/not-found", { kind: "not-found", session: null })
};
await writeFile(
  new URL("static-pages.js", dir),
  `// Generated by web/prerender.mjs.\nexport const ORIGIN_TOKEN = ${JSON.stringify(ORIGIN_TOKEN)};\nexport default ${JSON.stringify(pages)};\n`
);
console.log(`pre-rendered ${Object.keys(pages).join(", ")}`);
